namespace ConsoulLibrary
{
    /// <summary>
    /// Describes a relative cursor movement direction for Spectre-style cursor APIs.
    /// </summary>
    public enum CursorDirection
    {
        /// <summary>
        /// Moves the cursor upward.
        /// </summary>
        Up,

        /// <summary>
        /// Moves the cursor downward.
        /// </summary>
        Down,

        /// <summary>
        /// Moves the cursor left.
        /// </summary>
        Left,

        /// <summary>
        /// Moves the cursor right.
        /// </summary>
        Right
    }
}
