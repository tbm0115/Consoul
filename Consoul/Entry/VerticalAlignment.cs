namespace ConsoulLibrary
{
    /// <summary>
    /// Describes vertical alignment for renderable content inside a bounded height.
    /// </summary>
    public enum VerticalAlignment
    {
        /// <summary>
        /// Aligns content to the top edge.
        /// </summary>
        Top,

        /// <summary>
        /// Aligns content in the middle.
        /// </summary>
        Middle,

        /// <summary>
        /// Aligns content to the bottom edge.
        /// </summary>
        Bottom
    }
}
